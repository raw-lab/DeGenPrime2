#!/usr/bin/env bash
# Build the Windows resources that give degenprime.exe its icon and version
# details (Explorer, the taskbar and file Properties show them):
#   assets/windows/degenprime.res             linked by MSVC (and lld-link)
#   assets/windows/degenprime-x86_64-gnu.o    linked by the MinGW toolchain
# build.rs passes the right one to the linker; nothing is needed at build time.
# Run this after scripts/make_icon.py or a version change. Needs LLVM's
# llvm-rc and llvm-cvtres (Ubuntu: sudo apt install llvm).
set -euo pipefail
cd "$(dirname "$0")/.."
VERSION="$(grep -m1 '^version' Cargo.toml | cut -d'"' -f2)"
IFS=. read -r MA MI PA <<< "$VERSION"
RC_BIN="$(command -v llvm-rc || command -v llvm-rc-18 || command -v llvm-rc-17 || true)"
CVTRES="$(command -v llvm-cvtres || command -v llvm-cvtres-18 || command -v llvm-cvtres-17 || true)"
[ -n "$RC_BIN" ] && [ -n "$CVTRES" ] || { echo "error: llvm-rc and llvm-cvtres are needed (sudo apt install llvm)" >&2; exit 1; }
W=assets/windows
cp assets/icon.ico "$W/degenprime.ico"
cat > "$W/degenprime.rc" <<RC
// DeGenPrime $VERSION: icon and version information for degenprime.exe.
// Generated by scripts/make_windows_resource.sh.
#pragma code_page(65001)
1 ICON "degenprime.ico"

1 VERSIONINFO
FILEVERSION $MA,$MI,$PA,0
PRODUCTVERSION $MA,$MI,$PA,0
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "RAW Lab, University of North Carolina at Charlotte"
            VALUE "FileDescription", "DeGenPrime: degenerate PCR primer design"
            VALUE "FileVersion", "$VERSION"
            VALUE "InternalName", "degenprime"
            VALUE "LegalCopyright", "Copyright (c) 2026 Richard Allen White III"
            VALUE "OriginalFilename", "degenprime.exe"
            VALUE "ProductName", "DeGenPrime"
            VALUE "ProductVersion", "$VERSION"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
RC
( cd "$W" && "$RC_BIN" /nologo /fo degenprime.res degenprime.rc )
# A fixed timestamp keeps the object file reproducible.
"$CVTRES" /machine:x64 /timestamp:0 /out:"$W/degenprime-x86_64-gnu.o" "$W/degenprime.res" >/dev/null
rm -f "$W/degenprime.ico"
ls -l "$W"
